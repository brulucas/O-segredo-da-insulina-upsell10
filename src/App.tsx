import React, { useState, useEffect, useRef } from 'react';
import { Message, UserProfile, ThemeMode, NotificationSettings } from './types';
import {
  loadProfile,
  saveProfile,
  loadMessages,
  saveMessages,
  loadSavedChips,
  saveChips,
  loadThemeMode,
  saveThemeMode,
  loadNotificationSettings,
  saveNotificationSettings,
  clearAllData,
  DEFAULT_PROFILE,
} from './utils/storage';
import {
  streamHelenaChat,
  triggerBackgroundMemoryUpdate,
  fetchProactiveCheckin,
  getCurrentTime,
  getCurrentDate,
  generateId,
} from './utils/geminiChat';
import { useOnlineStatus } from './hooks/useOnlineStatus';
import { Header } from './components/Header';
import { DoodleBackground } from './components/DoodleBackground';
import { MessageBubble } from './components/MessageBubble';
import { TypingIndicator } from './components/TypingIndicator';
import { QuickReplies } from './components/QuickReplies';
import { InputBar } from './components/InputBar';
import { InstallModal } from './components/InstallModal';
import { InstallPromptNotification } from './components/InstallPromptNotification';
import { UserDataModal } from './components/UserDataModal';
import { SettingsModal } from './components/SettingsModal';
import { AboutModal } from './components/AboutModal';
import { WifiOff } from 'lucide-react';

export default function App() {
  const [profile, setProfile] = useState<UserProfile>(loadProfile);
  const [messages, setMessages] = useState<Message[]>(loadMessages);
  const [chips, setChips] = useState<string[]>(loadSavedChips);
  const [themeMode, setThemeMode] = useState<ThemeMode>(loadThemeMode);
  const [notificationSettings, setNotificationSettings] =
    useState<NotificationSettings>(loadNotificationSettings);

  const [isTyping, setIsTyping] = useState(false);
  const [streamingBalloons, setStreamingBalloons] = useState<string[]>([]);
  const [modalState, setModalState] = useState<{
    userData: boolean;
    install: boolean;
    settings: boolean;
    about: boolean;
  }>({
    userData: false,
    install: false,
    settings: false,
    about: false,
  });

  const isOnline = useOnlineStatus();
  const messagesEndRef = useRef<HTMLDivElement>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);
  const isFirstLoadRef = useRef(true);

  // System dark mode listener
  const [systemIsDark, setSystemIsDark] = useState(() =>
    typeof window !== 'undefined'
      ? window.matchMedia('(prefers-color-scheme: dark)').matches
      : false
  );

  useEffect(() => {
    const media = window.matchMedia('(prefers-color-scheme: dark)');
    const listener = (e: MediaQueryListEvent) => setSystemIsDark(e.matches);
    media.addEventListener('change', listener);
    return () => media.removeEventListener('change', listener);
  }, []);

  const isDark =
    themeMode === 'dark' || (themeMode === 'system' && systemIsDark);

  useEffect(() => {
    if (isDark) {
      document.documentElement.classList.add('dark');
    } else {
      document.documentElement.classList.remove('dark');
    }
  }, [isDark]);

  // Persist messages & profile & chips
  useEffect(() => {
    saveMessages(messages);
  }, [messages]);

  useEffect(() => {
    saveProfile(profile);
  }, [profile]);

  useEffect(() => {
    saveChips(chips);
  }, [chips]);

  const scrollToBottom = (smooth = true) => {
    messagesEndRef.current?.scrollIntoView({
      behavior: smooth ? 'smooth' : 'auto',
    });
  };

  useEffect(() => {
    scrollToBottom();
  }, [messages, streamingBalloons, isTyping]);

  // Initialization: If fresh start, trigger Helena's first message from AI in real time
  useEffect(() => {
    if (!isFirstLoadRef.current) return;
    isFirstLoadRef.current = false;

    if (messages.length === 0) {
      // Rule #1: First message is generated by Gemini in real time!
      sendAIFirstGreeting();
    } else {
      // Check for proactive check-in if user has been away
      checkProactiveReturn();
    }
  }, []);

  const sendAIFirstGreeting = async () => {
    setIsTyping(true);
    setStreamingBalloons([]);

    try {
      const result = await streamHelenaChat({
        history: [],
        userProfile: profile,
        isFirstMessage: true,
        onPartialBalloons: (partial) => {
          setStreamingBalloons(partial);
        },
        onChips: (receivedChips) => {
          setChips(receivedChips);
        },
      });

      // Commit finalized balloons to message history
      const time = getCurrentTime();
      const date = getCurrentDate();
      const newMessages: Message[] = result.balloons.map((txt) => ({
        id: generateId(),
        sender: 'persona',
        text: txt,
        time,
        date,
        read: true,
      }));

      setMessages(newMessages);
      setChips(result.chips);
    } catch (err: any) {
      const fallbackMsg: Message = {
        id: generateId(),
        sender: 'persona',
        text: err?.message || 'Deu uma falha aqui, me manda de novo?',
        time: getCurrentTime(),
        date: getCurrentDate(),
        read: true,
      };
      setMessages([fallbackMsg]);
    } finally {
      setIsTyping(false);
      setStreamingBalloons([]);
    }
  };

  const checkProactiveReturn = async () => {
    const lastActive = profile.lastActiveTimestamp || Date.now();
    const hoursAway = (Date.now() - lastActive) / (1000 * 60 * 60);

    // If away for more than 4 hours, Helena initiates conversation proactively
    if (hoursAway >= 4) {
      setIsTyping(true);
      try {
        const result = await fetchProactiveCheckin(profile, hoursAway);
        const time = getCurrentTime();
        const date = getCurrentDate();
        const newMsgs: Message[] = result.balloons.map((txt) => ({
          id: generateId(),
          sender: 'persona',
          text: txt,
          time,
          date,
          read: true,
        }));

        setMessages((prev) => [...prev, ...newMsgs]);
        if (result.chips.length > 0) {
          setChips(result.chips);
        }
        setProfile((prev) => ({ ...prev, lastActiveTimestamp: Date.now() }));
      } catch (e) {
        // Silent fail on proactive check-in
      } finally {
        setIsTyping(false);
      }
    }
  };

  // Send a user message (text or plate photo)
  const handleSendMessage = async (
    text: string,
    image?: { mimeType: string; data: string }
  ) => {
    if (!text.trim() && !image) return;

    const time = getCurrentTime();
    const date = getCurrentDate();

    const userMsg: Message = {
      id: generateId(),
      sender: 'user',
      text: text.trim(),
      time,
      date,
      read: true,
      image: image ? `data:${image.mimeType};base64,${image.data}` : undefined,
      status: 'sent',
    };

    const updatedHistory = [...messages, userMsg];
    setMessages(updatedHistory);
    setChips([]); // Clear chips while waiting for AI response
    setIsTyping(true);
    setStreamingBalloons([]);

    try {
      const result = await streamHelenaChat({
        message: text.trim(),
        image,
        history: updatedHistory,
        userProfile: profile,
        onPartialBalloons: (partial) => {
          setStreamingBalloons(partial);
        },
        onChips: (receivedChips) => {
          setChips(receivedChips);
        },
      });

      // Commit finalized AI bubbles
      const replyTime = getCurrentTime();
      const replyDate = getCurrentDate();
      const aiMsgs: Message[] = result.balloons.map((txt) => ({
        id: generateId(),
        sender: 'persona',
        text: txt,
        time: replyTime,
        date: replyDate,
        read: true,
      }));

      const finalHistory = [...updatedHistory, ...aiMsgs];
      setMessages(finalHistory);
      setChips(result.chips);

      // Trigger background memory update without blocking the user
      triggerBackgroundMemoryUpdate(finalHistory, profile, (updatedProf) => {
        setProfile(updatedProf);
      });
    } catch (err: any) {
      console.error('Chat error:', err);
      const errorMsg: Message = {
        id: generateId(),
        sender: 'persona',
        text: err?.message || 'Deu uma falha aqui, me manda de novo?',
        time: getCurrentTime(),
        date: getCurrentDate(),
        read: true,
      };
      setMessages((prev) => [...prev, errorMsg]);
    } finally {
      setIsTyping(false);
      setStreamingBalloons([]);
      setProfile((prev) => ({ ...prev, lastActiveTimestamp: Date.now() }));
    }
  };

  const [showResetConfirm, setShowResetConfirm] = useState(false);

  const confirmResetChat = () => {
    clearAllData();
    setProfile(DEFAULT_PROFILE);
    setMessages([]);
    setChips([]);
    setShowResetConfirm(false);
    sendAIFirstGreeting();
  };

  const handleResetChat = () => {
    setShowResetConfirm(true);
  };

  const handleThemeChange = (mode: ThemeMode) => {
    setThemeMode(mode);
    saveThemeMode(mode);
  };

  const handleUpdateNotifications = (settings: NotificationSettings) => {
    setNotificationSettings(settings);
    saveNotificationSettings(settings);
  };

  // Render messages grouped with date markers
  const renderChatItems = () => {
    let lastDate = '';

    return (
      <>
        {messages.map((msg, index) => {
          const showDateDivider = msg.date && msg.date !== lastDate;
          if (msg.date) lastDate = msg.date;

          return (
            <React.Fragment key={msg.id || index}>
              {showDateDivider && (
                <div className="flex justify-center my-3 select-none">
                  <span
                    className={`px-3 py-1 rounded-lg text-[11px] font-medium shadow-2xs ${
                      isDark
                        ? 'bg-[#182229] text-[#8696a0]'
                        : 'bg-[#ffffff] text-[#54656f]'
                    }`}
                  >
                    {msg.date === getCurrentDate() ? 'Hoje' : msg.date}
                  </span>
                </div>
              )}
              <MessageBubble
                message={msg}
                isDark={isDark}
                showTail={
                  index === messages.length - 1 ||
                  messages[index + 1]?.sender !== msg.sender
                }
              />
            </React.Fragment>
          );
        })}

        {/* Live streaming bubbles as they close in real time */}
        {isTyping && streamingBalloons.length > 0 && (
          <>
            {streamingBalloons.map((balloonText, bIdx) => (
              <MessageBubble
                key={`stream-${bIdx}`}
                message={{
                  id: `stream-${bIdx}`,
                  sender: 'persona',
                  text: balloonText,
                  time: getCurrentTime(),
                  date: getCurrentDate(),
                  read: true,
                }}
                isDark={isDark}
                showTail={bIdx === streamingBalloons.length - 1}
              />
            ))}
          </>
        )}

        {/* Typing indicator when waiting for first token or between balloons */}
        {isTyping && streamingBalloons.length === 0 && (
          <TypingIndicator isDark={isDark} />
        )}
      </>
    );
  };

  return (
    <div
      className={`min-h-screen flex flex-col justify-between font-sans antialiased overflow-hidden ${
        isDark ? 'bg-[#0b141a] text-[#e9edef]' : 'bg-[#efeae2] text-[#111b21]'
      }`}
    >
      {/* Offline Toast Banner */}
      {!isOnline && (
        <div className="bg-amber-500 text-white text-xs py-1 px-4 text-center flex items-center justify-center space-x-1.5 z-50 shadow-sm animate-in fade-in select-none">
          <WifiOff className="w-3.5 h-3.5" />
          <span>Sem internet. O histórico salvo continua disponível!</span>
        </div>
      )}

      {/* Main Single Chat Shell */}
      <div className="relative flex flex-col h-screen max-w-2xl mx-auto w-full shadow-2xl">
        {/* Header */}
        <Header
          userProfile={profile}
          isTyping={isTyping}
          isDark={isDark}
          onOpenData={() =>
            setModalState((prev) => ({ ...prev, userData: true }))
          }
          onOpenInstall={() =>
            setModalState((prev) => ({ ...prev, install: true }))
          }
          onOpenSettings={() =>
            setModalState((prev) => ({ ...prev, settings: true }))
          }
          onOpenAbout={() =>
            setModalState((prev) => ({ ...prev, about: true }))
          }
          onResetChat={handleResetChat}
        />

        {/* WhatsApp Chat Wallpaper with Doodles */}
        <div className="relative flex-1 overflow-y-auto overflow-x-hidden flex flex-col p-2 select-text">
          <DoodleBackground isDark={isDark} />

          <div className="relative z-10 flex-1 flex flex-col pb-2">
            {renderChatItems()}
            <div ref={messagesEndRef} />
          </div>
        </div>

        {/* AI-Generated Dynamic Quick Replies (Chips from ###CHIPS###) */}
        <QuickReplies
          isDark={isDark}
          chips={chips}
          disabled={isTyping}
          onSelectReply={(text) => handleSendMessage(text)}
        />

        {/* Bottom WhatsApp Input Bar */}
        <InputBar
          isDark={isDark}
          onSendMessage={handleSendMessage}
          disabled={isTyping}
          fileInputRef={fileInputRef}
        />
      </div>

      {/* Entry Install Prompt Popup (Requested by user) */}
      <InstallPromptNotification
        isDark={isDark}
        onOpenGuide={() =>
          setModalState((prev) => ({ ...prev, install: true }))
        }
      />

      {/* Modals for Menu Items */}
      <InstallModal
        isOpen={modalState.install}
        onClose={() => setModalState((prev) => ({ ...prev, install: false }))}
        isDark={isDark}
      />

      <UserDataModal
        isOpen={modalState.userData}
        onClose={() => setModalState((prev) => ({ ...prev, userData: false }))}
        isDark={isDark}
        userProfile={profile}
        onClearData={handleResetChat}
      />

      <SettingsModal
        isOpen={modalState.settings}
        onClose={() => setModalState((prev) => ({ ...prev, settings: false }))}
        isDark={isDark}
        themeMode={themeMode}
        onThemeChange={handleThemeChange}
        notificationSettings={notificationSettings}
        onUpdateNotifications={handleUpdateNotifications}
      />

      <AboutModal
        isOpen={modalState.about}
        onClose={() => setModalState((prev) => ({ ...prev, about: false }))}
        isDark={isDark}
      />

      {/* Confirmation modal for clearing chat without window.confirm */}
      {showResetConfirm && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-xs animate-in fade-in select-none">
          <div
            className={`w-full max-w-sm rounded-2xl p-5 shadow-2xl border ${
              isDark
                ? 'bg-[#202c33] border-[#2f3b43] text-[#e9edef]'
                : 'bg-white border-gray-200 text-[#111b21]'
            }`}
          >
            <h3 className="font-bold text-base mb-2">Apagar conversa e memória?</h3>
            <p className="text-xs opacity-75 mb-4 leading-relaxed">
              Todas as mensagens e o histórico de memória serão apagados do seu aparelho. A Helena reiniciará a conversa do zero.
            </p>
            <div className="flex items-center justify-end space-x-2">
              <button
                onClick={() => setShowResetConfirm(false)}
                className={`px-3.5 py-1.5 rounded-lg text-xs font-medium ${
                  isDark ? 'hover:bg-white/10 text-gray-300' : 'hover:bg-gray-100 text-gray-600'
                }`}
              >
                Cancelar
              </button>
              <button
                onClick={confirmResetChat}
                className="px-3.5 py-1.5 rounded-lg text-xs font-semibold bg-rose-600 hover:bg-rose-700 text-white shadow-xs"
              >
                Apagar
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
